BOUND = r'A-Za-z0-9ÄÖÜäöüÀ-ÿ'

def build_pattern(key):
    parts = [re.escape(w) for w in key.split()]
    pat = r'\s+'.join(parts)
    if re.match(r'[' + BOUND + ']', key):
        pat = r'(?<![' + BOUND + r'])' + pat
    if re.search(r'[' + BOUND + r']$', key):
        pat = pat + r'(?![' + BOUND + r'])'
    return re.compile(pat)

def translate(html, idx):
    entries = sorted(T, key=lambda e: -len(e[0]))
    for e in entries:
        html = build_pattern(e[0]).sub(lambda m: e[idx], html)
    return html

def lang_switcher(lang, page, footer=False):
    cls = 'langsw langsw--footer' if footer else 'langsw'
    tag = 'span' if footer else 'div'
    label = {'fr': 'Langue', 'it': 'Lingua', 'en': 'Language', 'de': 'Sprache'}[lang]
    items = []
    for l in ['de', 'fr', 'it', 'en']:
        href = ('../' + page) if l == 'de' else ((page) if l == lang else ('../' + l + '/' + page))
        active = ' class="is-active" aria-current="true"' if l == lang else (' lang="' + l + '"')
        items.append('<a href="' + href + '"' + active + '>' + l.upper() + '</a>')
    return '<' + tag + ' class="' + cls + '" aria-label="' + label + '">' + ''.join(items) + '</' + tag + '>'

def js_obj(d):
    import json
    return json.dumps(d, ensure_ascii=False)

def main():
    import json
    idx_map = {'fr': 1, 'it': 2, 'en': 3}
    for lang, cfg in LANGS.items():
        outdir = os.path.join(ROOT, lang)
        os.makedirs(outdir, exist_ok=True)
        for page in PAGES:
            html = open(os.path.join(ROOT, page)).read()
            # 1) html lang
            html = html.replace('<html lang="de-CH">', '<html lang="' + cfg['html_lang'] + '">', 1)
            # 2) asset paths -> ../
            # insights/ liegt nur auf Deutsch im Wurzelverzeichnis. Ohne den
            # Eintrag hier würde der Fusslink aus fr/index.html auf
            # /fr/insights/ zeigen und ins Leere laufen.
            html = re.sub(r'(href|src)="(css/|js/|assets/|insights/)', r'\1="../\2', html)
            # 3) language switchers (replace the German blocks wholesale)
            html = re.sub(r'<div class="langsw"[^>]*>.*?</div>', lang_switcher(lang, page), html, flags=re.S)
            html = re.sub(r'<span class="langsw langsw--footer"[^>]*>.*?</span>', lang_switcher(lang, page, footer=True), html, flags=re.S)
            # 3b) self-referencing canonical and og:url. Without this every
            # language would claim https://llmify.ch/ as its canonical, which
            # tells Google the three translations are duplicates of the German
            # page — they would drop out of the index. The hreflang block is
            # identical on all four pages by design and stays untouched.
            page_url = SITE + lang + '/' + page
            html = html.replace('<link rel="canonical" href="' + SITE + '">',
                                '<link rel="canonical" href="' + page_url + '">', 1)
            html = html.replace('<meta property="og:url" content="' + SITE + '">',
                                '<meta property="og:url" content="' + page_url + '">', 1)
            html = html.replace('<meta property="og:locale" content="de_CH">',
                                '<meta property="og:locale" content="' + cfg['og_locale'] + '">', 1)
            # inLanguage im JSON-LD (WebSite und SoftwareApplication). Steht dort
            # als Sprach-Tag, nicht als Text, und wird deshalb nicht von T erfasst.
            html = html.replace('"inLanguage": "de-CH"',
                                '"inLanguage": "' + cfg['html_lang'] + '"')

            # 4) translate
            html = translate(html, idx_map[lang])
            # 5) composer placeholder + I18N for the demo (index only)
            html = html.replace('</title>', '</title>\n  <style>:root{--msg-ph:"' + cfg['placeholder'] + '"}</style>', 1)
            if page == 'index.html':
                html = html.replace('<script src="../js/main.js">',
                                    '<script>window.I18N = ' + js_obj(I18N_JS[lang]) + ';</script>\n  <script src="../js/main.js">', 1)
            open(os.path.join(outdir, page), 'w').write(html)
            print(lang + '/' + page, 'written')

